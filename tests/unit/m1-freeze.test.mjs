/**
 * The problems that make a module text not inert. Words are looked for outside JSON string
 * literals only, so that prose such as "an important new standard" in a summary is not mistaken
 * for code; inside a string literal nothing can execute.
 */
function inertProblems(text, file) {
  const problems = [];
  const newline = text.indexOf('\n');
  const header = newline >= 0 ? text.slice(0, newline) : text;
  if (!HEADER.test(header)) problems.push(`${file}: first line is not the fixed freeze header`);
  const body = newline >= 0 ? text.slice(newline + 1) : '';
  const m = /^export default ([\s\S]*);\n$/.exec(body);
  if (!m) {
    problems.push(`${file}: body is not "export default <literal>;" followed by one newline`);
    return problems;
  }
  const outsideStrings = body.replace(/"(?:[^"\\\n]|\\.)*"/g, '""');
  const exportsCount = (outsideStrings.match(/\bexport\b/g) || []).length;
  if (exportsCount !== 1) problems.push(`${file}: ${exportsCount} export statements`);
  for (const [what, re] of [['import', /\bimport\b/], ['function', /\bfunction\b/], ['=>', /=>/], ['new ', /\bnew /], ['backtick', /`/]]) {
    if (re.test(outsideStrings)) problems.push(`${file}: contains ${what}`);
  }
  try {
    JSON.parse(m[1]);
  } catch (error) {
    problems.push(`${file}: the exported value is not a plain literal (${error.message})`);
  }
  return problems;
}

test('M1-U14 every expected-data module is inert', async () => {
  const manifest = (await import(repoUrl('tests/fixtures/expected-data/freeze.js').href)).default;
  // Guard: the check must recognise code, or it could not fail.
  const bad = `// Frozen at G3 on 2026-10-05 from pipeline/output/. Generated by pipeline/freeze-core.mjs; do not edit by hand.\nexport default (() => 1)();\n`;
  assert.ok(inertProblems(bad, 'guard').length > 0, 'an arrow function is detected');
  const problems = [];
  for (const p of manifest.modules) {
    const file = `tests/fixtures/expected-data/${p.slice('data/'.length)}`;
    problems.push(...inertProblems(await readText(repoUrl(file)), file));
  }
  assert.none(problems, 'non-inert modules');
});

