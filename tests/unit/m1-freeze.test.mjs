test('M1-U13 the freeze core is deterministic and its output equals the expected values', async () => {
  const core = await importUnderTest(CORE);
  const first = await runCore(core, await pipelineFixture());
  const second = await runCore(core, await pipelineFixture());
  assert.ok(first && first.ok === true && first.files instanceof Map, 'the fixture freezes');
  assert.deepEqual([...first.files.keys()].sort(), [...second.files.keys()].sort(), 'file set on a second run');
  for (const [p, text] of first.files) assert.equal(second.files.get(p), text, `second run, ${p}`);

  const manifest = (await import(repoUrl('tests/fixtures/expected-data/freeze.js').href)).default;
  assert.deepEqual([...first.files.keys()].sort(), [...manifest.modules].sort(), 'files produced against the expected manifest');
  for (const p of manifest.modules) {
    const expected = (await import(repoUrl(`tests/fixtures/expected-data/${p.slice('data/'.length)}`).href)).default;
    assert.deepEqual(parseModule(first.files.get(p)), expected, p);
  }
});

