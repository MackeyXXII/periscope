test('M1-U16 every entity in data/ has a pass verdict whose hash matches its canonical JSON', { needs: ['data'] }, async () => {
  const verification = await importJson(repoUrl('pipeline/output/verification.json'));
  const content = await loadContent({ from: 'data' });
  const entities = [
    ...content.signals,
    ...content.trends,
    ...Object.values(content.reveal).flatMap((b) => [...b.readings, b.interrogation]),
    ...Object.values(content.conversation),
    ...content.log,
    content.readiness,
    content.governance,
    content.brief,
  ];
  const problems = [];
  for (const entity of entities) {
    const hash = await entityHash(entity);
    const verdicts = (verification.entities || []).filter((v) => v.id === entity.id);
    if (!verdicts.some((v) => v.verdict === 'pass' && v.hash === hash)) {
      problems.push(`${entity.id}: no pass verdict with hash ${hash} (found ${JSON.stringify(verdicts.map((v) => [v.verdict, v.hash]))})`);
    }
  }
  assert.none(problems, 'entities without a matching pass verdict');
});
